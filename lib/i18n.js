export function lookup(lang, key) {
  return dict[lang]?.[key] ?? dict.id[key] ?? key;
}

export function interpolate(str, vars) {
  if (!vars) return str;
  return Object.entries(vars).reduce(
    (s, [k, v]) => s.split(`{${k}}`).join(String(v)),
    str
  );
}
